import { fileURLToPath } from "node:url";
import { z } from "zod";
import { readJson } from "../_shared/json";
import { AppCategoryLabelSchema, GameCategoryLabelSchema, type LlmType } from "./category";

const LLM_CLASSIFICATIONS_PATH = fileURLToPath(
  new URL("../../../config/llm-classifications.json", import.meta.url),
);

const entryBase = z.object({
  id: z
    .string()
    .describe("The CatalogApp id this classification was assigned to, e.g. 'pacman-aur:wings3d'."),
  confidence: z
    .enum(["high", "medium", "low"])
    .describe(
      "The LLM's own certainty in this classification. A three-level enum rather than a numeric score — self-reported LLM probabilities are poorly calibrated, so a finer scale would only pretend to precision. 'low' entries are kept for auditability but never applied (see llmClassificationMap).",
    ),
  reason: z.string().describe("Why the LLM assigned this classification — for auditability."),
  model: z
    .string()
    .describe(
      "The model that produced this entry, e.g. 'gemini-3.8-flash' or 'openai/gpt-oss-20b' — classify-llm rotates across config/llm-models.json's models to spread their free tiers' per-model quotas, so quality can be audited per model.",
    ),
});

/**
 * One LLM classification for a single app. Keyed by the app's own
 * `CatalogApp.id` — not a name glob like `category-rules.json` — because the LLM classifies
 * each *app* individually, and an id (already unique and stable across
 * rebuilds) avoids the generic-name collision trap a bare-name key would
 * reintroduce (see `match/group.ts`'s GENERIC_NAME_BLOCKLIST).
 *
 * The LLM answers the `type` — `app`, `game`, `library` or `other` — and,
 * for `app`/`game` only, a `category` from *that type's own* closed set
 * (app categories for an `app`, genres for a `game`). The union is
 * discriminated on `type`, so an entry pairing `type: "app"` with a genre,
 * or giving a `library` a category, fails validation. How much say an
 * entry gets against the deterministic signals is `enrichApps`'s call:
 * upstream store categories > LLM > the in-house heuristics.
 */
const LlmClassificationEntrySchema = z.discriminatedUnion("type", [
  entryBase.extend({
    type: z.literal("app"),
    category: AppCategoryLabelSchema.describe("One of the app categories."),
  }),
  entryBase.extend({
    type: z.literal("game"),
    category: GameCategoryLabelSchema.describe("One of the game genres."),
  }),
  entryBase
    .extend({
      type: z
        .literal("library")
        .describe("Code for other programs to use (libraries, headers, bindings) — never shown."),
    })
    .strict(),
  entryBase
    .extend({
      type: z
        .literal("other")
        .describe(
          "Not a program a user runs (data, fonts, themes, docs, add-ons, metapackages, test packages) — never shown.",
        ),
    })
    .strict(),
]);

/** Entries at this confidence are never applied — a wrong category is worse than an honest unknown. */
const UNAPPLIED_CONFIDENCE = "low";

/**
 * The only confidence at which a `library`/`other` verdict hides an app:
 * hiding a real app costs more than showing a library, so a `medium` one
 * leaves the app visible under its deterministic type.
 */
export const HIDE_CONFIDENCE = "high";

export type LlmClassificationEntry = z.infer<typeof LlmClassificationEntrySchema>;

export const LlmClassificationsListSchema = z.array(LlmClassificationEntrySchema).meta({
  title: "Enrich: LLM classifications",
  description:
    "LLM-assigned type (app, game, library or other) and, for apps and games, a category. In enrichApps, upstream store categories win over it and it wins over the in-house heuristics; 'library'/'other' hide the app at high confidence. Generated by `pnpm classify-llm` (free-tier LLMs, see config/llm-models.json), committed and consumed at build time; never hand-edited.",
});

/** Loads the LLM classification list (`config/llm-classifications.json`, missing file reads as empty). */
export function loadLlmClassifications(): LlmClassificationEntry[] {
  return readJson(LLM_CLASSIFICATIONS_PATH, LlmClassificationsListSchema);
}

/** What an applied (not low-confidence) LLM entry says about an app — `category` only for `app`/`game`. */
export interface LlmClassification {
  type: LlmType;
  category?: string;
  confidence: "high" | "medium";
}

/** A fast id → classification lookup built once per enrich pass, so the per-app lookup is O(1). Skips low-confidence entries — see `UNAPPLIED_CONFIDENCE`. */
export function llmClassificationMap(
  entries: LlmClassificationEntry[],
): Map<string, LlmClassification> {
  const map = new Map<string, LlmClassification>();
  for (const entry of entries) {
    if (entry.confidence === UNAPPLIED_CONFIDENCE) continue;
    map.set(entry.id, {
      type: entry.type,
      category: "category" in entry ? entry.category : undefined,
      confidence: entry.confidence,
    });
  }
  return map;
}
